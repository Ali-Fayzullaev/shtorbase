-- ============================================
-- Шаг 25: Realtime для доски заказов
-- ============================================
-- Сотрудники должны видеть новые/изменённые заказы на доске без ручного
-- обновления страницы. Используем встроенный Supabase Realtime (WebSocket
-- поверх Postgres logical replication) вместо периодического опроса —
-- это штатный механизм платформы, не требует своей инфраструктуры и не
-- создаёт лишнюю нагрузку на 5 пользователей опросом каждые N секунд.

alter publication supabase_realtime add table public.orders;
