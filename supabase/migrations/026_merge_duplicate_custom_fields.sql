-- ============================================
-- Шаг 26: Слияние дублей custom_fields «Цвет»/«цвет»/«Цветь»
-- ============================================
-- prepareVariantFields искал существующее поле по точному регистру имени
-- (.eq('name', ...)), поэтому «цвет» и «Цветь» (опечатка) для категории
-- «Шторы» превратились в ДВА разных поля с непересекающимися списками
-- опций — товар с сохранённым значением «Красный» (поле «Цветь») физически
-- не мог выбрать «Белый» из выпадающего списка, потому что «Белый» лежал
-- в СОСЕДНЕМ поле «цвет», а не в том, что реально использует товар.
--
-- Сливаем «Цветь» в «цвет» для категории «Шторы»: переносим ссылки
-- product_custom_values, объединяем options, удаляем дубль.

update product_custom_values
set field_id = '5c5d59bc-2418-47dc-97d5-c10986fb096b' -- канонический «Цвет» (категория «Шторы»)
where field_id = '44a427b7-df36-424d-8008-7e2acc3f4bd6'; -- дубль «Цветь»

update custom_fields
set name = 'Цвет',
    options = (
      select jsonb_agg(distinct v)
      from jsonb_array_elements_text(to_jsonb(options) || '["Красный"]'::jsonb) as v
    )
where id = '5c5d59bc-2418-47dc-97d5-c10986fb096b';

delete from custom_fields where id = '44a427b7-df36-424d-8008-7e2acc3f4bd6';

-- Страховка на будущее: не даём завести два поля с одинаковым именем
-- (без учёта регистра) в одной категории — независимо от того, какой
-- код их создаёт.
create unique index if not exists custom_fields_name_category_ci_unique
  on custom_fields (lower(name), coalesce(category_id, '00000000-0000-0000-0000-000000000000'::uuid));
